-- 1. leads 留资表 ---------------------------------------------
create table if not exists public.leads (
  id          bigint generated by default as identity primary key,
  name        text not null,
  contact     text not null,
  role        text not null,              -- 修理厂/汽配商/平台企业/AI公司/其他
  demand      text not null,              -- 知识库/数据产品/SOP/报告/课程/咨询/SaaS/AI合作
  description text,
  utm         jsonb default '{}'::jsonb,  -- utm_source/utm_medium/utm_campaign/... + referrer
  status      text not null default 'new',-- new/contacted/won/closed
  created_at  timestamptz not null default now()
);

-- 2. products 产品表 ------------------------------------------
create table if not exists public.products (
  id                   bigint generated by default as identity primary key,
  slug                 text unique not null,
  name                 text not null,
  icon                 text default 'package',
  layer                text not null check (layer in ('traffic','trust','conversion','delivery')),
  category             text not null,     -- knowledge/courses/reports/consulting/partners
  positioning          text not null,
  problem              text not null,     -- 解决什么问题
  audience             text not null,     -- 适合谁
  deliverable          text not null,     -- 交付什么
  price                text not null,     -- 怎么收费
  cta_type             text not null check (cta_type in ('claim','buy','consult')),
  third_party_url      text,              -- 第三方成交链接（官网自动附加 UTM）
  third_party_platform text,
  sort                 int default 0,
  created_at           timestamptz not null default now()
);

-- 3. contents 内容表 ------------------------------------------
create table if not exists public.contents (
  id        bigint generated by default as identity primary key,
  title     text not null,
  type      text not null,                -- 短视频/图文/直播回放
  platform  text not null,                -- 抖音/视频号/B站/公众号
  link      text,
  summary   text,
  cover     text,                         -- 封面图 URL
  metric    text,                         -- 播放/阅读数据
  date      text,
  created_at timestamptz not null default now()
);

-- 4. cases 案例表 ----------------------------------------------
create table if not exists public.cases (
  id        bigint generated by default as identity primary key,
  client    text not null,
  "group"   text not null,                -- 修理厂与经销商/从业者与团队/平台企业与AI
  problem   text not null,
  solution  text not null,
  metrics   jsonb default '[]'::jsonb,     -- [{label, value}]
  logo      text,
  created_at timestamptz not null default now()
);

-- 5. partners 合作方表 -----------------------------------------
create table if not exists public.partners (
  id               bigint generated by default as identity primary key,
  name             text not null,
  logo             text,
  cooperation_type text,
  created_at       timestamptz not null default now()
);

